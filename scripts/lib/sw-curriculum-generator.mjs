import assert from "node:assert/strict";

function nonEmptyString(value, label) {
  assert.equal(typeof value, "string", `${label} must be a string`);
  assert.ok(value.trim(), `${label} must not be empty`);
  return value;
}

function uniqueValues(values, label) {
  assert.equal(new Set(values).size, values.length, `${label} must be unique`);
}

export function normalizedSwCurriculum(sourceValue) {
  const source = structuredClone(sourceValue);
  assert.equal(source?.schemaVersion, 1, "SW curriculum schemaVersion must be 1");
  nonEmptyString(source.fieldId, "fieldId");
  nonEmptyString(source.contentScope, "contentScope");
  assert.ok(Array.isArray(source.subjectGroups) && source.subjectGroups.length > 0, "subjectGroups are required");
  assert.ok(Array.isArray(source.recommendations), "recommendations must be an array");

  const groupIds = [];
  const subjectIds = [];
  const subjectNames = [];
  for (const [groupIndex, group] of source.subjectGroups.entries()) {
    const label = `subjectGroups[${groupIndex}]`;
    groupIds.push(nonEmptyString(group.id, `${label}.id`));
    assert.match(group.id, /^[a-z0-9]+(?:-[a-z0-9]+)*$/u, `${label}.id must be kebab-case`);
    nonEmptyString(group.name, `${label}.name`);
    nonEmptyString(group.summary, `${label}.summary`);
    assert.ok(Array.isArray(group.subjects) && group.subjects.length > 0, `${label}.subjects are required`);
    for (const [subjectIndex, subject] of group.subjects.entries()) {
      const subjectLabel = `${label}.subjects[${subjectIndex}]`;
      subjectIds.push(nonEmptyString(subject.id, `${subjectLabel}.id`));
      subjectNames.push(nonEmptyString(subject.name, `${subjectLabel}.name`));
      assert.match(subject.id, /^[a-z0-9]+(?:-[a-z0-9]+)*$/u, `${subjectLabel}.id must be kebab-case`);
      nonEmptyString(subject.summary, `${subjectLabel}.summary`);
      assert.ok(Array.isArray(subject.topics) && subject.topics.length > 0, `${subjectLabel}.topics are required`);
      subject.topics.forEach((topic, topicIndex) => nonEmptyString(topic, `${subjectLabel}.topics[${topicIndex}]`));
      uniqueValues(subject.topics, `${subjectLabel}.topics`);
    }
  }
  uniqueValues(groupIds, "SW curriculum group ids");
  uniqueValues(subjectIds, "SW curriculum subject ids");
  uniqueValues(subjectNames, "SW curriculum subject names");
  const subjectIdSet = new Set(subjectIds);

  const recommendationIds = [];
  const questionProfiles = [];
  const recommendations = source.recommendations.map((recommendation, index) => {
    const label = `recommendations[${index}]`;
    recommendationIds.push(nonEmptyString(recommendation.id, `${label}.id`));
    assert.match(recommendation.id, /^[a-z0-9]+(?:-[a-z0-9]+)*$/u, `${label}.id must be kebab-case`);
    nonEmptyString(recommendation.name, `${label}.name`);
    nonEmptyString(recommendation.summary, `${label}.summary`);
    assert.ok(Array.isArray(recommendation.subjectIds) && recommendation.subjectIds.length > 0, `${label}.subjectIds are required`);
    uniqueValues(recommendation.subjectIds, `${label}.subjectIds`);
    for (const subjectId of recommendation.subjectIds) {
      assert.ok(subjectIdSet.has(subjectId), `${label} references unknown subject ${subjectId}`);
    }
    if (recommendation.questionProfile) {
      const profile = recommendation.questionProfile;
      nonEmptyString(profile.requiredTag, `${label}.questionProfile.requiredTag`);
      nonEmptyString(profile.selectionMessage, `${label}.questionProfile.selectionMessage`);
      assert.ok(Array.isArray(profile.phaseTags) && profile.phaseTags.length > 0, `${label}.questionProfile.phaseTags are required`);
      profile.phaseTags.forEach((tag, tagIndex) => nonEmptyString(tag, `${label}.questionProfile.phaseTags[${tagIndex}]`));
      uniqueValues(profile.phaseTags, `${label}.questionProfile.phaseTags`);
      questionProfiles.push({
        id: recommendation.id,
        recommendationId: recommendation.id,
        subjectIds: recommendation.subjectIds,
        requiredTag: profile.requiredTag,
        phaseTags: profile.phaseTags,
        selectionMessage: profile.selectionMessage,
      });
    }
    return {
      id: recommendation.id,
      name: recommendation.name,
      summary: recommendation.summary,
      subjectIds: recommendation.subjectIds,
      ...(recommendation.questionProfile ? { questionProfileId: recommendation.id } : {}),
    };
  });
  uniqueValues(recommendationIds, "SW curriculum recommendation ids");
  uniqueValues(questionProfiles.map((profile) => profile.requiredTag), "SW curriculum profile required tags");

  return {
    schemaVersion: source.schemaVersion,
    fieldId: source.fieldId,
    contentScope: source.contentScope,
    subjectGroups: source.subjectGroups,
    recommendations,
    subjectIds,
    questionProfiles,
  };
}

function runtimeModule(curriculum) {
  return `// Generated by scripts/generate-sw-curriculum.mjs from sw-curriculum.source.json.\n// Do not edit this file directly.\n\nfunction deepFreeze(value) {\n  if (value && typeof value === "object" && !Object.isFrozen(value)) {\n    for (const nested of Object.values(value)) deepFreeze(nested);\n    Object.freeze(value);\n  }\n  return value;\n}\n\nexport const SW_CURRICULUM_SCHEMA_VERSION = ${curriculum.schemaVersion};\nexport const SW_CURRICULUM_FIELD_ID = ${JSON.stringify(curriculum.fieldId)};\nexport const SW_CURRICULUM_CONTENT_SCOPE = ${JSON.stringify(curriculum.contentScope)};\nexport const SW_CURRICULUM_SUBJECT_GROUPS = deepFreeze(${JSON.stringify(curriculum.subjectGroups, null, 2)});\nexport const SW_CURRICULUM_RECOMMENDATIONS = deepFreeze(${JSON.stringify(curriculum.recommendations, null, 2)});\nexport const SW_CURRICULUM_SUBJECT_IDS = deepFreeze(${JSON.stringify(curriculum.subjectIds, null, 2)});\nexport const SW_CURRICULUM_QUESTION_PROFILES = deepFreeze(${JSON.stringify(curriculum.questionProfiles, null, 2)});\n\nconst QUESTION_PROFILE_REGISTRY = deepFreeze(Object.fromEntries(\n  SW_CURRICULUM_QUESTION_PROFILES.map((profile) => [profile.id, profile]),\n));\n\nexport function swCurriculumQuestionProfile(value) {\n  return QUESTION_PROFILE_REGISTRY[String(value ?? "")] ?? null;\n}\n\nexport function swCurriculumQuestionProfileForSubjects(subjectIds) {\n  const selected = new Set(Array.isArray(subjectIds) ? subjectIds : []);\n  return SW_CURRICULUM_QUESTION_PROFILES.find((profile) => (\n    profile.subjectIds.length === selected.size\n      && profile.subjectIds.every((subjectId) => selected.has(subjectId))\n  )) ?? null;\n}\n`;
}

function summaryRuntimeModule(curriculum) {
  const groups = curriculum.subjectGroups.map((group) => ({
    id: group.id,
    name: group.name,
    summary: group.summary,
    subjects: group.subjects.map((subject) => ({
      id: subject.id,
      name: subject.name,
      summary: subject.summary,
      topics: [],
    })),
  }));
  return `// Generated by scripts/generate-sw-curriculum.mjs from sw-curriculum.source.json.
// Do not edit this file directly.

function deepFreeze(value) {
  if (value && typeof value === "object" && !Object.isFrozen(value)) {
    for (const nested of Object.values(value)) deepFreeze(nested);
    Object.freeze(value);
  }
  return value;
}

export const SW_CURRICULUM_SUMMARY_SUBJECT_GROUPS = deepFreeze(${JSON.stringify(groups, null, 2)});
export const SW_CURRICULUM_SUMMARY_RECOMMENDATIONS = deepFreeze(${JSON.stringify(curriculum.recommendations, null, 2)});
export const SW_CURRICULUM_SUMMARY_SUBJECT_IDS = deepFreeze(${JSON.stringify(curriculum.subjectIds, null, 2)});
`;
}

