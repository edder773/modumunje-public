function declarationsModule(curriculum) {
  const subjectIdUnion = curriculum.subjectIds.map(JSON.stringify).join(" | ");
  return `// Generated by scripts/generate-sw-curriculum.mjs from sw-curriculum.source.json.\n// Do not edit this file directly.\n\nexport type SwCurriculumSubjectId = ${subjectIdUnion};\nexport type SwCurriculumSubject = Readonly<{ id: SwCurriculumSubjectId; name: string; summary: string; topics: readonly string[] }>;\nexport type SwCurriculumSubjectGroup = Readonly<{ id: string; name: string; summary: string; subjects: readonly SwCurriculumSubject[] }>;\nexport type SwCurriculumRecommendation = Readonly<{ id: string; name: string; summary: string; subjectIds: readonly SwCurriculumSubjectId[]; questionProfileId?: string }>;\nexport type SwCurriculumQuestionProfile = Readonly<{ id: string; recommendationId: string; subjectIds: readonly SwCurriculumSubjectId[]; requiredTag: string; phaseTags: readonly string[]; selectionMessage: string }>;\n\nexport const SW_CURRICULUM_SCHEMA_VERSION: ${curriculum.schemaVersion};\nexport const SW_CURRICULUM_FIELD_ID: ${JSON.stringify(curriculum.fieldId)};\nexport const SW_CURRICULUM_CONTENT_SCOPE: ${JSON.stringify(curriculum.contentScope)};\nexport const SW_CURRICULUM_SUBJECT_GROUPS: readonly SwCurriculumSubjectGroup[];\nexport const SW_CURRICULUM_RECOMMENDATIONS: readonly SwCurriculumRecommendation[];\nexport const SW_CURRICULUM_SUBJECT_IDS: readonly SwCurriculumSubjectId[];\nexport const SW_CURRICULUM_QUESTION_PROFILES: readonly SwCurriculumQuestionProfile[];\nexport function swCurriculumQuestionProfile(value: unknown): SwCurriculumQuestionProfile | null;\nexport function swCurriculumQuestionProfileForSubjects(subjectIds: unknown): SwCurriculumQuestionProfile | null;\n`;
}

function pythonModule(curriculum) {
  const rows = curriculum.subjectGroups.flatMap((group) => group.subjects.map((subject) => (
    `    ${JSON.stringify(subject.name)}: (${JSON.stringify(group.id)}, ${JSON.stringify(subject.id)}),`
  ))).join("\n");
  return `# Generated by scripts/generate-sw-curriculum.mjs from sw-curriculum.source.json.\n# Do not edit this file directly.\n\nSUBJECTS = {\n${rows}\n}\n`;
}

export function buildSwCurriculumArtifacts(source) {
  const curriculum = normalizedSwCurriculum(source);
  return {
    curriculum,
    runtime: runtimeModule(curriculum),
    declarations: declarationsModule(curriculum),
    summaryRuntime: summaryRuntimeModule(curriculum),
    summaryDeclarations: summaryDeclarationsModule(),
    python: pythonModule(curriculum),
  };
}
